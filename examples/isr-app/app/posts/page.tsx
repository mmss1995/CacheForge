import { unstable_cache } from 'next/cache'

// Rendered at runtime (not at build) so the first request fills the shared cache.
export const dynamic = 'force-static'
export const revalidate = 3600
export const dynamicParams = true

let generation = 0

// The "database": every call that is not served from cache produces a new generation number.
const getPosts = unstable_cache(
  async () => {
    generation += 1
    return {
      generatedBy: process.env.INSTANCE_ID ?? 'local',
      generation,
      generatedAt: new Date().toISOString(),
      posts: ['Hello', 'World'],
    }
  },
  ['posts'],
  { tags: ['posts'], revalidate: 3600 },
)

export default async function Posts() {
  const data = await getPosts()
  // Demo on purpose: shows render time next to the cached generation time.
  // oxlint-disable-next-line react/purity
  const renderedAt = new Date().toISOString()
  return (
    <main>
      <h1>Posts</h1>
      <ul>
        {data.posts.map((p) => (
          <li key={p}>{p}</li>
        ))}
      </ul>
      <p>
        data generated by <b id="generated-by">{data.generatedBy}</b> (generation{' '}
        <b id="generation">{data.generation}</b>) at <span id="generated-at">{data.generatedAt}</span>
      </p>
      <p>
        page rendered by <b id="rendered-by">{process.env.INSTANCE_ID ?? 'local'}</b> at{' '}
        <span id="rendered-at">{renderedAt}</span>
      </p>
    </main>
  )
}
