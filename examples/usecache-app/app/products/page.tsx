import { Suspense } from 'react'
import { connection } from 'next/server'
import { cacheLife, cacheTag } from 'next/cache'

let generation = 0

async function getProducts() {
  'use cache: remote'
  cacheTag('products')
  cacheLife({ stale: 5, revalidate: 3600, expire: 86400 })
  generation += 1
  return {
    generatedBy: process.env.INSTANCE_ID ?? 'local',
    generation,
    generatedAt: new Date().toISOString(),
    items: ['Keyboard', 'Mouse'],
  }
}

async function Products() {
  // Opt out of build-time prerendering: the cache fills at runtime, from the first request.
  await connection()
  const data = await getProducts()
  return (
    <>
      <ul>
        {data.items.map((p) => (
          <li key={p}>{p}</li>
        ))}
      </ul>
      <p>
        generated by <b id="generated-by">{data.generatedBy}</b> (generation{' '}
        <b id="generation">{data.generation}</b>) at <span id="generated-at">{data.generatedAt}</span>
      </p>
    </>
  )
}

export default function ProductsPage() {
  return (
    <main>
      <h1>Products</h1>
      <Suspense fallback={<p>loading…</p>}>
        <Products />
      </Suspense>
    </main>
  )
}
